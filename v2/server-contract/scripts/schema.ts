/**
 * Generates `shared/src/generated/schema.json`: the JSON Schema of every shared type the server
 * reads or writes, made from the valibot schemas in `shared/` (the protocol's source of truth).
 * The Rust server (`server-rs/`) embeds this file and checks what arrives with it — hellos,
 * pings, routing envelopes, library maps, game backups — so both servers refuse the same input.
 *
 * Run: `bun run schema` (writes the file); `bun test ./generated.check.ts` fails when the file
 * is stale.
 *
 * `finite` is left out of the schema on purpose: JSON can't carry NaN or Infinity, so every JSON
 * number is finite already. Every other valibot action must convert (the conversion throws).
 *
 * @see ../../docs/server-rs.md "wire types"
 */
import { toJsonSchemaDefs } from '@valibot/to-json-schema';
import { join } from 'node:path';
import * as S from '../../shared/src/index.ts';

/** Where the generated file goes. */
export const SCHEMA_PATH = join(import.meta.dir, '..', '..', 'shared', 'src', 'generated', 'schema.json');

/** The shared schemas the server uses, by the name the Rust side looks them up with. */
const DEFS = {
  Id: S.Id,
  FileExt: S.FileExt,
  FileRef: S.FileRef,
  RasterGrid: S.RasterGrid,
  MapInfo: S.MapInfo,
  LibraryEntry: S.LibraryEntry,
  GameSummary: S.GameSummary,
  Game: S.Game,
  Role: S.Role,
  Peer: S.Peer,
  Hello: S.Hello,
  Ping: S.Ping,
  Welcome: S.Welcome,
  Pong: S.Pong,
  PeerJoined: S.PeerJoined,
  PeerLeft: S.PeerLeft,
  Replaced: S.Replaced,
  Undelivered: S.Undelivered,
  ServerBuild: S.ServerBuild,
  ServerError: S.ServerError,
  ServerMessage: S.ServerMessage,
  ClientControl: S.ClientControl,
  RoutingEnvelope: S.RoutingEnvelope,
};

/**
 * Builds the schema document.
 *
 * @returns the JSON text (two-space indent, trailing newline)
 * @throws {Error} when a valibot schema uses something JSON Schema can't express
 */
export function buildSchema(): string {
  const defs = toJsonSchemaDefs(DEFS, { target: 'draft-2020-12', errorMode: 'throw', ignoreActions: ['finite'] });
  const doc = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $comment: 'GENERATED by server-contract/scripts/schema.ts from shared/src (valibot) — do not edit; run `bun run schema` in server-contract.',
    'x-constants': {
      protocolVersion: S.PROTOCOL_VERSION,
      serverMessageTypes: [...S.SERVER_MESSAGE_TYPES].sort(),
    },
    $defs: defs,
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

if (import.meta.main) {
  await Bun.write(SCHEMA_PATH, buildSchema());
  console.info(`wrote ${SCHEMA_PATH}`);
}
